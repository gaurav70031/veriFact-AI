def _lazy_import(module_path, attr):
    """Return a lazy-importing wrapper for a function."""
    def _wrapper(*args, **kwargs):
        import importlib
        mod = importlib.import_module(module_path)
        fn  = getattr(mod, attr)
        return fn(*args, **kwargs)
    _wrapper.__name__ = attr
    _wrapper.__doc__  = "Lazy import of {}.{}".format(module_path, attr)
    return _wrapper


