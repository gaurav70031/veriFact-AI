# -*- coding: utf-8 -*-
"""
ml - VeriFact AI Machine Learning Engine
=========================================

Package structure
-----------------
ml/
  __init__.py            <- this file - top-level re-exports
  data_loader.py         <- unified dataset loading
  preprocessing_api.py   <- unified text cleaning
  feature_extraction.py  <- TF-IDF feature inspection + transformer tokenization
  predict.py             <- unified prediction (all models + ensemble)
  evaluation.py          <- unified evaluation and results loading

  preprocessing/         <- raw preprocessing pipeline
    cleaner.py           <- text cleaning (baseline + transformer modes)
    loader.py            <- multi-format dataset reader
    labels.py            <- label normalisation (raw string -> 0/1)
    deduplication.py     <- exact + near-dup removal + leakage detection
    splitter.py          <- stratified train/val/test split
    stats.py             <- dataset statistics
    pipeline.py          <- orchestrator: load -> clean -> dedup -> split -> save
    config.py            <- paths + hyperparameters

  baseline/              <- TF-IDF + sklearn models
    config.py            <- hyperparameters + artifact paths
    trainer.py           <- Pipeline builders + train_single/train_all
    inference.py         <- predict_single/predict_all_models/predict_batch
    evaluator.py         <- evaluate_pipeline/evaluate_all + metrics
    __init__.py

  transformer/           <- DistilBERT / BERT fine-tuning
    config.py            <- base model, chunking, training hyperparameters
    dataset.py           <- FakeNewsDataset + ChunkedArticleDataset
    trainer.py           <- full training loop with early stopping
    inference.py         <- predict_text with overlapping chunk aggregation
    evaluator.py         <- evaluate() on batched test loader
    __init__.py

  saved_models/          <- artifact directory (created at runtime)
    lr_pipeline.pkl
    svm_pipeline.pkl
    nb_pipeline.pkl
    distilbert/
      v1.0.0/
        config.json
        pytorch_model.bin (or model.safetensors)
        tokenizer/
        training_record.json
    eval/
      lr_eval.json
      svm_eval.json
      nb_eval.json
      all_models_eval.json
      distilbert_eval.json

  datasets/
    raw/                 <- place Fake.csv + True.csv here before running
    processed/           <- generated by scripts/prepare_dataset.py
      train.csv
      val.csv
      test.csv
      dataset_stats.json

Quick-start usage
-----------------
  # 1. Prepare dataset
  python scripts/prepare_dataset.py \\
      --files ml/datasets/raw/Fake.csv ml/datasets/raw/True.csv

  # 2. Train baseline models
  python scripts/train_baseline.py

  # 3. Evaluate baseline models
  python scripts/evaluate_baseline.py

  # 4. Train DistilBERT (GPU recommended)
  python scripts/train_transformer.py

  # 5. Evaluate DistilBERT
  python scripts/evaluate_transformer.py

  # 6. Run a prediction
  from ml.predict import predict_ensemble
  result = predict_ensemble('The moon landing was faked by NASA.')
  print(result['label'], result['confidence'])

Models trained on
-----------------
ISOT Fake News Dataset (Ahmed et al., 2018)
  ~44,900 articles | 52.3% fake | 47.7% real
  Stratified 80/10/10 split | random_state=42

No model weights are included in this repository.
Run the training scripts after downloading the ISOT dataset from:
  https://www.kaggle.com/datasets/clmentbisaillon/fake-and-real-news-dataset
"""

